export function getPlatformLogoData(platform: string, customServices?: { id: string; name: string; color: string }[]): { path: string; viewBox: string } | null {
  // Tier 1: built-in
  if (LOGO_PATHS[platform]) {
    const d = LOGO_PATHS[platform];
    return { path: d.path, viewBox: d.viewBox || '0 0 24 24' };
  }

  // Tier 2: suggested — match by custom service name
  if (customServices) {
    const svc = customServices.find(s => s.id === platform);
    if (svc) {
      const key = SUGGESTED_NAME_MAP[svc.name.toLowerCase()];
      if (key && SUGGESTED_LOGOS[key]) {
        const d = SUGGESTED_LOGOS[key];
        return { path: d.path, viewBox: d.viewBox || '0 0 24 24' };
      }
    }
  }

  return null; // Tier 3: custom — no logo
}

const PlatformLogo = ({ platform, size = 16, className = '' }: PlatformLogoProps) => {
  const data = getPlatformLogoData(platform);
  if (!data) return null;

  return (
    <svg
      viewBox={data.viewBox}
      width={size}
      height={size}
      fill="currentColor"
      className={className}
      aria-hidden="true"
    >
      <path d={data.path} />
    </svg>
  );
};

